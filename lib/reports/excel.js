// ── Formula injection protection ────────────────────────────────────
// Any string starting with = + - @ is prefixed with a single quote so
// Excel treats it as literal text (prevents CSV/Excel formula injection
// via customer/product/address/SKU/imported text fields).
const DANGEROUS = /^[=+\-@]/i
export function safeText(v) {
  if (v === null || v === undefined) return ''
  if (typeof v === 'number') return v
  const s = String(v)
  if (DANGEROUS.test(s)) return `'${s}`
  return s
}

const num = (v) => Number(v) || 0
const dtStr = (iso) => {
  if (!iso) return ''
  const d = new Date(iso)
  if (isNaN(d.getTime())) return ''
  return d.toLocaleString('en-IN', { day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit', hour12: true })
}
const timeStr = (iso) => {
  if (!iso) return ''
  const d = new Date(iso)
  if (isNaN(d.getTime())) return ''
  return d.toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit', hour12: true })
}
const deliveryStatus = (st) => {
  if (st === 'delivered') return 'Delivered'
  if (st === 'out_for_delivery') return 'Out for Delivery'
  if (st === 'shipped') return 'Shipped'
  if (st === 'packed') return 'Packed'
  if (['cancelled', 'rejected', 'vendor_rejected', 'admin_rejected'].includes(st)) return 'Cancelled'
  if (st === 'returned') return 'Returned'
  return 'In Progress'
}

function headerStyle(cell) {
  cell.font = { bold: true, color: { argb: 'FFFFFFFF' }, size: 10, name: 'Calibri' }
  cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: `FF${BRAND.primary}` } }
  cell.alignment = { vertical: 'middle', horizontal: 'center', wrapText: true }
  cell.border = { bottom: { style: 'thin', color: { argb: 'FFC9962C' } } }
}
function bandedStyle(cell, rowIdx) {
  if (rowIdx % 2 === 0) {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: `FF${BRAND.alt}` } }
  }
}
function titleBlock(ws, report, ncols) {
  const meta = report.meta
  const lastCol = columnLetter(ncols)
  ws.mergeCells(`A1:${lastCol}1`)
  ws.getCell('A1').value = 'AK ENTERPRISES'
  ws.getCell('A1').font = { bold: true, size: 16, color: { argb: `FF${BRAND.primary}` } }
  ws.getCell('A1').fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: `FF${BRAND.goldLight}` } }
  ws.getCell('A1').alignment = { vertical: 'middle', horizontal: 'left', indent: 1 }
  ws.getRow(1).height = 24

  ws.mergeCells(`A2:${lastCol}2`)
  ws.getCell('A2').value = meta.reportName
  ws.getCell('A2').font = { bold: true, size: 13 }
  ws.getCell('A2').alignment = { vertical: 'middle', horizontal: 'left', indent: 1 }
  ws.getRow(2).height = 20

  ws.mergeCells(`A3:${lastCol}3`)
  const lines = [
    `Generated At: ${dtStr(meta.generatedAt)}   |   Zone: ${meta.zoneName}   |   Period: ${meta.dateRangeLabel}   |   Currency: ${CURRENCY}`,
    `Generated By: ${meta.generatedBy || 'AK Enterprises'}   |   Timezone: ${REPORT_TIMEZONE}   |   Filters: ${filterLabel(meta.filters)}`
  ]
  ws.getCell('A3').value = lines[0]
  ws.getCell('A3').font = { size: 9, color: { argb: `FF${BRAND.muted}` } }
  ws.getCell('A3').alignment = { vertical: 'middle', horizontal: 'left', indent: 1 }
  ws.mergeCells(`A4:${lastCol}4`)
  ws.getCell('A4').value = lines[1]
  ws.getCell('A4').font = { size: 9, color: { argb: `FF${BRAND.muted}` } }
  ws.getCell('A4').alignment = { vertical: 'middle', horizontal: 'left', indent: 1 }
  ws.getRow(5).height = 6
}
function filterLabel(f) {
  if (!f) return 'None'
  const parts = []
  if (f.status && f.status !== 'all') parts.push(`Status: ${f.status}`)
  if (f.payment_status && f.payment_status !== 'all') parts.push(`Payment: ${f.payment_status}`)
  if (f.brand) parts.push(`Brand: ${f.brand}`)
  if (f.category_id) parts.push(`Category: ${f.category_id}`)
  if (f.state) parts.push(`State: ${f.state}`)
  if (f.city) parts.push(`City: ${f.city}`)
  if (f.zone_id) parts.push(`Zone: ${f.zone_id}`)
  if (parts.length === 0) parts.push('All orders')
  return parts.join(' · ')
}
function columnLetter(n) {
  let s = ''
  while (n > 0) {
    const rem = (n - 1) % 26
    s = String.fromCharCode(65 + rem) + s
    n = Math.floor((n - 1) / 26)
  }
  return s
}

// ── Generic tabular sheet writer ─────────────────────────────────────
// rows: array of objects keyed by column.key. columns may carry
// {header, key, width, numFmt, sum, align, wrap, cond}.
function writeDataSheet(wb, opts) {
  const { name, title, subtitle, columns, rows, totalsKeys, banded = true, landscape = true } = opts
  const ws = wb.addWorksheet(name, { pageSetup: { orientation: landscape ? 'landscape' : 'portrait', fitToWidth: 1, fitToHeight: 0, paperSize: 9, printArea: `A1:${columnLetter(columns.length)}${rows.length + 7}` } })
  ws.pageSetup.printTitlesRow = '1:6'
  ws.pageSetup.margins = { left: 0.3, right: 0.3, top: 0.5, bottom: 0.5, header: 0.2, footer: 0.2 }
  ws.properties.defaultRowHeight = 18

  // columns widths
  ws.columns = columns.map((c) => ({ width: c.width || 12, key: c.key }))

  // title block occupies rows 1..5, header at row 6, data from row 7
  titleBlock(ws, opts.report, columns.length)

  const hdrRow = 6
  ws.getRow(hdrRow).values = columns.map((c) => c.header)
  ws.getRow(hdrRow).eachCell((cell) => headerStyle(cell))
  ws.getRow(hdrRow).height = 26

  let r = hdrRow + 1
  for (let i = 0; i < rows.length; i++) {
    const row = rows[i]
    const rowObj = ws.getRow(r)
    columns.forEach((c, ci) => {
      let v = row[c.key]
      if (typeof v === 'function') v = v(row)
      if (typeof v === 'string' && !c.numFmt) v = safeText(v)
      const cell = rowObj.getCell(ci + 1)
      cell.value = v
      if (c.numFmt) cell.numFmt = c.numFmt
      if (banded) bandedStyle(cell, r)
      cell.alignment = { vertical: 'top', horizontal: c.align || 'left', wrapText: c.wrap !== false }
      if (c.cond) applyCondStyle(cell, c.cond, v)
    })
    r++
  }

  // totals row
  if (totalsKeys && totalsKeys.length) {
    const rowObj = ws.getRow(r)
    columns.forEach((c, ci) => {
      if (c.key === 'totals_label') {
        rowObj.getCell(ci + 1).value = 'TOTAL'
      } else if (totalsKeys.includes(c.key)) {
        const sum = rows.reduce((s, row) => s + num(row[c.key]), 0)
        rowObj.getCell(ci + 1).value = round2(sum)
        rowObj.getCell(ci + 1).numFmt = c.numFmt || FMT.inr
      } else {
        rowObj.getCell(ci + 1).value = ''
      }
      rowObj.getCell(ci + 1).font = { bold: true }
      rowObj.getCell(ci + 1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: `FF${BRAND.goldLight}` } }
    })
    r++
  }

  // freeze panes + autofilter
  ws.views = [{ state: 'frozen', ySplit: hdrRow }]
  if (rows.length > 0) {
    ws.autoFilter = { from: { row: hdrRow, column: 1 }, to: { row: r - 1, column: columns.length } }
  }

  // conditional formatting (cell-based rules) — applied across data range
  const lastRow = Math.max(hdrRow + 1, r - 1)
  for (const c of columns) {
    if (c.cond && c.cond.rules) {
      const ci = columnLetter(columns.indexOf(c) + 1)
      ws.addConditionalFormatting({
        ref: `${ci}${hdrRow + 1}:${ci}${Math.min(lastRow, hdrRow + 1000)}`,
        rules: c.cond.rules.map((rule) => ({
          type: rule.type || 'cellIs',
          operator: rule.operator || 'equal',
          formulae: rule.formulae || [''],
          style: rule.style || {}
        }))
      })
    }
  }

  return ws
}

// Conditional style for cell-based colouring (statuses).
function applyCondStyle(cell, cond, value) {
  if (!cond || cond.map) return
  if (cond.rules) return // handled by Excel conditional formatting
}

// ── KPI label/value pair ─────────────────────────────────────────────
function kv(ws, row, label, value, fmt = FMT.num, bold = false, section = false) {
  const lc = ws.getCell(`A${row}`)
  const vc = ws.getCell(`B${row}`)
  if (section) {
    lc.value = label.toUpperCase()
    lc.font = { bold: true, color: { argb: `FF${BRAND.white}` } }
    lc.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: `FF${BRAND.gold}` } }
    vc.value = ''
    return
  }
  lc.value = label
  lc.font = { size: 10, color: { argb: `FF${BRAND.muted}` } }
  vc.value = value
  vc.numFmt = fmt
  vc.font = { bold: bold, size: 10 }
  lc.border = { bottom: { style: 'hair', color: { argb: 'FFE5E7EB' } } }
  vc.border = { bottom: { style: 'hair', color: { argb: 'FFE5E7EB' } } }
}

