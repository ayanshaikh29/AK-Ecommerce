function buildSalesSummary(wb, report) {
  const s = report.summary
  const ws = wb.addWorksheet('Sales Summary', { pageSetup: { orientation: 'landscape', fitToWidth: 1, paperSize: 9 } })
  ws.columns = [{ width: 34 }, { width: 20 }, { width: 30 }, { width: 20 }]
  titleBlock(ws, report, 4)

  let r = 6
  kv(ws, r++, 'KEY METRICS', '', null, false, true)
  const kpi = [
    ['Total Orders', s.totalOrders, FMT.num0],
    ['Total Unique Customers', s.uniqueCustomers, FMT.num0],
    ['Total Products Sold', s.totalProductsSold, FMT.num0],
    ['Total Delivered Products', s.totalDeliveredProducts, FMT.num0],
    ['New Customers', s.newCustomers, FMT.num0],
    ['Repeat Customers', s.repeatCustomers, FMT.num0],
    ['Gross Sales', s.grossSales, FMT.inr],
    ['Taxable Amount', s.taxableAmount, FMT.inr],
    ['Total Discounts', s.totalDiscounts, FMT.inr],
    ['Total GST', s.totalGST, FMT.inr],
    ['Total Shipping Charges', s.totalShipping, FMT.inr],
    ['Total Refunds', s.totalRefunds, FMT.inr],
    ['Returns Value', s.totalReturnsValue, FMT.inr],
    ['Net Revenue', s.netRevenue, FMT.inr],
    ['Average Order Value (net)', s.avgOrderValue, FMT.inr],
    ['Avg Items Per Order', s.avgItemsPerOrder, FMT.num],
    ['Avg Customer Order Value', s.avgCustomerOrderValue, FMT.inr]
  ]
  for (const [label, val, fmt] of kpi) kv(ws, r++, label, val, fmt, true)

  kv(ws, r++, '', '', null, false, false)
  kv(ws, r++, 'ORDER STATUS', '', null, false, true)
  const statusRows = [
    ['Delivered Orders', s.deliveredOrders],
    ['Pending Orders', s.pendingOrders],
    ['Processing Orders', s.processingOrders],
    ['Shipped / Out for Delivery', s.shippedOrders],
    ['Cancelled / Rejected', s.cancelledOrders],
    ['Returned', s.returnedOrders]
  ]
  for (const [label, val] of statusRows) kv(ws, r++, label, val, FMT.num0)

  kv(ws, r++, '', '', null, false, false)
  kv(ws, r++, 'PAYMENT', '', null, false, true)
  const payRows = [
    ['Paid Orders', s.paidOrders],
    ['Unpaid / Pending Orders', s.unpaidOrders],
    ['Partially Paid Orders', s.partiallyPaidOrders]
  ]
  for (const [label, val] of payRows) kv(ws, r++, label, val, FMT.num0)

  kv(ws, r++, '', '', null, false, false)
  kv(ws, r++, 'RECONCILIATION', '', null, false, true)
  const rec = report.reconciliation || {}
  kv(ws, r++, 'Report Orders', rec.reportOrders ?? report.summary.totalOrders, FMT.num0)
  kv(ws, r++, 'Net Revenue (report)', rec.reportNetRevenue ?? report.summary.netRevenue, FMT.inr)
  kv(ws, r++, 'Orders-page revenue', rec.ordersPageRevenue ?? 0, FMT.inr)
  kv(ws, r++, 'Totals match', rec.revenueMatches === true ? 'YES' : 'MISMATCH', null, true)
  if (rec.revenueMatches !== true) {
    ws.getCell(`B${r - 1}`).font = { bold: true, color: { argb: `FF${BRAND.red}` } }
  }

  kv(ws, r++, '', '', null, false, false)
  kv(ws, r++, 'DATA QUALITY', '', null, false, true)
  const dq = report.dataQuality || {}
  kv(ws, r++, 'Lines missing GSTIN', dq.missingGstin ?? 0, FMT.num0)
  kv(ws, r++, 'Lines missing HSN code', dq.missingHsn ?? 0, FMT.num0)
  kv(ws, r++, 'Lines missing city', dq.missingCity ?? 0, FMT.num0)
  kv(ws, r++, 'Lines missing company', dq.missingCompany ?? 0, FMT.num0)
  kv(ws, r++, 'Lines missing zone', dq.missingZone ?? 0, FMT.num0)

  ws.views = [{ state: 'frozen', ySplit: 6 }]
  return ws
}

