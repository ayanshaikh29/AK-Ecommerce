/**
 * Builds the complete workbook from a report object (from query-service).
 * @returns {Promise<Buffer>}
 */
export async function buildWorkbook(report) {
  const wb = new ExcelJS.Workbook()
  wb.creator = report.meta.generatedBy || 'AK Enterprises'
  wb.lastModifiedBy = 'AK Enterprises Reports'
  wb.created = new Date()
  wb.modified = new Date()
  wb.company = 'AK Enterprises'
  wb.subject = 'Sales & Orders Report'
  wb.keywords = 'report, sales, orders, gst, excel'

  buildSalesSummary(wb, report)
  buildDefinitions(wb, report)
  buildOrderDetails(wb, report)
  buildOrdersSummary(wb, report)
  buildProductsSold(wb, report)
  buildSalesByDate(wb, report)
  buildSalesByProduct(wb, report)
  buildSalesByCategory(wb, report)
  buildSalesByCustomer(wb, report)
  buildSalesByLocation(wb, report)
  buildPaymentReport(wb, report)
  buildOrderStatusReport(wb, report)
  buildGSTReport(wb, report)
  buildDataQuality(wb, report)
  buildNotes(wb, report)

  return wb.xlsx.writeBuffer()
}

/** Safe export file name per spec: AK_Enterprises_Order_Report_YYYY-MM-DD_HH-mm.xlsx */
export function reportFileName(zoneName = '') {
  const d = new Date()
  const pad = (n) => String(n).padStart(2, '0')
  const stamp = `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}_${pad(d.getHours())}-${pad(d.getMinutes())}`
  const zone = zoneName ? `_${String(zoneName).replace(/[^a-zA-Z0-9_-]/g, '_')}` : ''
  return `AK_Enterprises_Order_Report${zone}_${stamp}.xlsx`
}
